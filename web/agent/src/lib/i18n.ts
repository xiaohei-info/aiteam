export function createAgentI18n(): I18n {
  const catalog = { ...sharedMessages };
  for (const [locale, msgs] of Object.entries(agentMessages)) {
    catalog[locale] = { ...(catalog[locale] ?? {}), ...msgs };
  }
  return createI18n({ catalog });
}
